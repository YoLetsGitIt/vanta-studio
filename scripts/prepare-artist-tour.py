"""Assemble one captioned, silent artist app tour from reviewed real recordings.

Run prepare-artist-demos.py first. Requires ffmpeg, ffprobe and Pillow.
ARTIST_TOUR_FONT can point to a local regular TrueType font.
"""
import json
import os
import subprocess
import tempfile
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'public/studio/artist/demos'
FONT = Path(os.environ.get('ARTIST_TOUR_FONT', str(Path.home() / 'Downloads/Plus Jakarta Sans Sora Space Grotesk/Space_Grotesk/static/SpaceGrotesk-Medium.ttf')))
SECTIONS = [
    ('portfolio', 'Your portfolio', 'Upload your work. Review the tags.', 'Keep unfinished pieces as drafts.'),
    ('discovery', 'Get discovered', 'From the feed to a closer look.', 'Style and placement help tell the story.'),
    ('requests', 'Booking requests', 'The design, placement and session details.', 'Read the brief before you reply.'),
    ('proposals', 'Quote & propose', 'Set your quote and session duration.', 'Choose a time that works.'),
    ('schedule', 'Your working hours', 'Set your weekly hours.', 'Make room for a day off.'),
    ('calendar', 'Your calendar', 'See requests and sessions by date.', 'Keep your week in view.'),
    ('analytics', 'Views & saves', 'See how your work is doing.', 'Tap a total for the full count.'),
]

def run(args):
    subprocess.run(['ffmpeg', '-v', 'error', '-y', *args], check=True)

def duration(path):
    return float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(path)]))

chapters = []
elapsed = 0
with tempfile.TemporaryDirectory(prefix='vanta-artist-tour-') as directory:
    tmp = Path(directory)
    calendar = tmp / 'calendar-source.mp4'
    run(['-ss', '3.1', '-i', str(ROOT.parent / 'demo/artist-tutorial/clips/09.mp4'), '-t', '3.2',
         '-vf', 'crop=432:966:1164:57,setsar=1,fps=30', '-an', '-c:v', 'libx264', '-crf', '20', str(calendar)])
    for index, (key, title, line1, line2) in enumerate(SECTIONS):
        source = calendar if key == 'calendar' else ASSETS / f'{key}.mp4'
        length = duration(source)
        card = Image.new('RGB', (520, 1180), '#11150f')
        draw = ImageDraw.Draw(card)
        draw.text((30, 17), 'VANTA / FOR ARTISTS', font=ImageFont.truetype(str(FONT), 13), fill='#baad92')
        draw.text((30, 39), title, font=ImageFont.truetype(str(FONT), 28), fill='#f5eddd')
        draw.text((30, 1080), line1, font=ImageFont.truetype(str(FONT), 20), fill='#f5eddd')
        draw.text((30, 1111), line2, font=ImageFont.truetype(str(FONT), 18), fill='#cabea8')
        draw.line((30, 1155, 490, 1155), fill='#3b3e32', width=2)
        draw.line((30, 1155, 30 + round(460 * (index + 1) / len(SECTIONS)), 1155), fill='#d9c398', width=2)
        card.save(tmp / f'{key}.png')
        run(['-loop', '1', '-framerate', '30', '-i', str(tmp / f'{key}.png'), '-i', str(source),
             '-filter_complex', f'[0:v][1:v]overlay=44:88:shortest=1,fade=t=in:d=0.16,fade=t=out:st={length-.16}:d=0.16,format=yuv420p[v]',
             '-map', '[v]', '-an', '-t', str(length), '-c:v', 'libx264', '-preset', 'slow', '-crf', '20', str(tmp / f'{key}.mp4')])
        chapters.append({'at': round(elapsed, 2), 'title': title})
        elapsed += length
    (tmp / 'playlist.txt').write_text(''.join(f"file '{key}.mp4'\n" for key, *_ in SECTIONS))
    output = ASSETS / 'artist-app-tour.mp4'
    run(['-f', 'concat', '-safe', '0', '-i', str(tmp / 'playlist.txt'), '-c', 'copy', '-movflags', '+faststart', str(output)])
    run(['-ss', '0.5', '-i', str(output), '-frames:v', '1', '-q:v', '2', str(ASSETS / 'artist-app-tour-poster.jpg')])

tour = dict(src='/studio/artist/demos/artist-app-tour.mp4', poster='/studio/artist/demos/artist-app-tour-poster.jpg',
            title='Meet Vanta for artists', duration=round(duration(output)), portrait=True, tour=True,
            context='Recorded in the Vanta app', chapters=chapters)
(ROOT / 'lib/artistAppTour.js').write_text('// Generated by scripts/prepare-artist-tour.py.\nexport const ARTIST_APP_TOUR = ' + json.dumps(tour, indent=2) + ';\n')
print(f'Tour: {duration(output):.1f}s, {output.stat().st_size // 1024} KB, {len(chapters)} chapters')
